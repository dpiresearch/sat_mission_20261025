# --------------------------------------------------------------------------- tools
def _host_allowed(host):
    host = (host or "").lower().rstrip(".")
    return any(host == d or host.endswith("." + d) for d in FETCH_ALLOW)


def _public_host(host):
    try:
        for info in socket.getaddrinfo(host, 443):
            ip = ipaddress.ip_address(info[4][0])
            if not ip.is_global:
                return False
        return True
    except OSError:
        return False


class _AllowlistRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        p = urllib.parse.urlparse(newurl)
        if p.scheme != "https" or not _host_allowed(p.hostname) or not _public_host(p.hostname):
            raise urllib.error.HTTPError(newurl, 403, "redirect to a non-allowlisted host", headers, fp)
        return super().redirect_request(req, fp, code, msg, headers, newurl)


_opener = urllib.request.build_opener(_AllowlistRedirect)


def _get(url, accept="*/*", limit=2_000_000):
    p = urllib.parse.urlparse(url)
    if p.scheme != "https" or not _host_allowed(p.hostname):
        raise ValueError(f"domain not allowed: {p.hostname}. Allowed: {', '.join(FETCH_ALLOW)}")
    if not _public_host(p.hostname):
        raise ValueError("host does not resolve to a public address")
    req = urllib.request.Request(url, headers={"User-Agent": UA, "Accept": accept})
    with _opener.open(req, timeout=15) as r:
        ctype = r.headers.get("Content-Type", "")
        return r.read(limit), ctype


def _html_to_text(raw):
    s = re.sub(r"(?is)<(script|style|noscript|svg|nav|footer)[^>]*>.*?</\1>", " ", raw)
    s = re.sub(r"(?i)<br\s*/?>|</(p|div|li|tr|h[1-6]|table|section|article)>", "\n", s)
    s = re.sub(r"(?i)</t[dh]>", " | ", s)
    s = re.sub(r"<[^>]+>", "", s)
    s = html.unescape(s)
    s = re.sub(r"[ \t\r\f\v]+", " ", s)
    return re.sub(r"\n\s*\n+", "\n", s).strip()


def tool_fetch_page(url, offset=0):
    body, ctype = _get(url, accept="text/html,text/plain,application/json;q=0.9,*/*;q=0.5")
    if "pdf" in ctype:
        return f"[{url} is a PDF ({len(body)} bytes); PDF text extraction is not available. Summarize from the page that links to it instead.]"
    text = body.decode("utf-8", errors="replace")
    if "html" in ctype or text.lstrip().startswith("<"):
        text = _html_to_text(text)
    offset = max(0, int(offset or 0))
    chunk = text[offset:offset + FETCH_LIMIT]
    more = len(text) - (offset + len(chunk))
    tail = f"\n\n[truncated: {more} more characters; call again with offset={offset + len(chunk)}]" if more > 0 else ""
    return f"URL: {url}\n\n{chunk}{tail}"


def _gh_api(path):
    body, _ = _get("https://api.github.com" + path, accept="application/vnd.github+json")
    return json.loads(body)


def tool_github_repo(repo, path=""):
    if not re.fullmatch(r"[\w.-]+/[\w.-]+", repo or ""):
        raise ValueError("repo must look like owner/name")
    path = (path or "").strip("/")
    data = _gh_api(f"/repos/{repo}/contents/{urllib.parse.quote(path)}")
    if isinstance(data, list):
        rows = [f"{'dir ' if d['type'] == 'dir' else 'file'}  {d['path']}" + (f"  ({d['size']} B)" if d["type"] == "file" else "")
                for d in data[:200]]
        return f"https://github.com/{repo}/tree/HEAD/{path}\n" + "\n".join(rows)
    if data.get("type") == "file":
        if data.get("size", 0) > 400_000:
            return f"{data['path']} is {data['size']} bytes, too large to read. Link: {data.get('html_url')}"
        raw, _ = _get(data["download_url"])
        text = raw.decode("utf-8", errors="replace")
        if "\x00" in text[:2000]:
            return f"{data['path']} is a binary file. Link: {data.get('html_url')}"
        extra = f"\n\n[truncated at {FETCH_LIMIT} of {len(text)} characters]" if len(text) > FETCH_LIMIT else ""
        return f"{data.get('html_url')}\n\n{text[:FETCH_LIMIT]}{extra}"
    return json.dumps(data)[:2000]


def tool_github_search_repos(query):
    q = urllib.parse.quote(query[:200])
    data = _gh_api(f"/search/repositories?q={q}&per_page=8")
    return "\n".join(f"- {r['full_name']} ★{r['stargazers_count']}: {r.get('description') or ''} ({r['html_url']})"
                     for r in data.get("items", [])) or "No repositories found."


def tool_wikipedia_search(query):
    q = urllib.parse.quote(query[:200])
    body, _ = _get(f"https://en.wikipedia.org/w/api.php?action=query&list=search&srsearch={q}&srlimit=5&format=json")
    hits = json.loads(body).get("query", {}).get("search", [])
    out = []
    for h in hits:
        snippet = html.unescape(re.sub(r"<[^>]+>", "", h.get("snippet", "")))
        url = "https://en.wikipedia.org/wiki/" + urllib.parse.quote(h["title"].replace(" ", "_"))
        out.append(f"- {h['title']} ({url}): {snippet}")
    return "\n".join(out) or "No results."


TOOL_FUNCS = {
    "fetch_page": lambda i: tool_fetch_page(i["url"], i.get("offset", 0)),
    "github_repo": lambda i: tool_github_repo(i["repo"], i.get("path", "")),
    "github_search_repos": lambda i: tool_github_search_repos(i["query"]),
    "wikipedia_search": lambda i: tool_wikipedia_search(i["query"]),
}


def run_tool(name, tool_input):
    try:
        return TOOL_FUNCS[name](tool_input), False
    except KeyError as e:
        return f"Missing or unknown parameter: {e}", True
    except urllib.error.HTTPError as e:
        return f"HTTP {e.code} fetching resource: {e.reason}", True
    except (urllib.error.URLError, socket.timeout, TimeoutError) as e:
        return f"Network error: {e}", True
    except (ValueError, json.JSONDecodeError) as e:
        return f"Error: {e}", True


# --------------------------------------------------------------------------- rate limits
def _bump(key, ttl_s):
    r = ddb.update_item(
        TableName=TABLE, Key={"k": {"S": key}},
        UpdateExpression="ADD n :one SET expires_at = if_not_exists(expires_at, :exp)",
        ExpressionAttributeValues={":one": {"N": "1"}, ":exp": {"N": str(int(time.time()) + ttl_s)}},
        ReturnValues="UPDATED_NEW",
    )
    return int(r["Attributes"]["n"]["N"])


def over_limit(ip):
    if not ddb:
        return None
    hour = time.strftime("%Y%m%d%H", time.gmtime())
    day = time.strftime("%Y%m%d", time.gmtime())
    if _bump(f"ip#{ip}#{hour}", 7200) > PER_IP_PER_HOUR:
        return "You've reached the hourly question limit for this site. Please try again later."
    if _bump(f"global#{day}", 172800) > GLOBAL_PER_DAY:
        return "The assistant has reached its daily limit. Please try again tomorrow."
    return None


# --------------------------------------------------------------------------- chat loop
def clean_history(raw):
    if not isinstance(raw, list) or not raw:
        raise ValueError("messages must be a non-empty list")
    msgs = []
    for m in raw[-MAX_TURNS:]:
        role, content = m.get("role"), m.get("content")
        if role not in ("user", "assistant") or not isinstance(content, str) or not content.strip():
            continue
        msgs.append({"role": role, "content": content[:MAX_CHARS]})
    while msgs and msgs[0]["role"] != "user":
        msgs.pop(0)
    if not msgs or msgs[-1]["role"] != "user":
        raise ValueError("the last message must be from the user")
    return msgs


def chat(messages):
    started = time.time()
    sources, activity = [], []
    state = BetaFallbackState()
    response = None
    with state:
        for _ in range(MAX_TOOL_ROUNDS + 1):
            response = client.beta.messages.create(
                model=MODEL,
                max_tokens=8000,
                output_config={"effort": "medium"},
                system=[{"type": "text", "text": SYSTEM, "cache_control": {"type": "ephemeral"}}],
                tools=TOOLS,
                messages=messages,
            )
            if response.stop_reason != "tool_use":
                break
            messages.append({"role": "assistant", "content": response.content})
            results = []
            out_of_time = time.time() - started > DEADLINE_S
            for block in response.content:
                if block.type != "tool_use":
                    continue
                if out_of_time:
                    text, err = "Time budget exhausted; answer with what you have.", True
                else:
                    text, err = run_tool(block.name, block.input)
                activity.append({"tool": block.name, "input": block.input, "ok": not err})
                url = block.input.get("url") or (f"https://github.com/{block.input['repo']}" if "repo" in block.input else None)
                if url and not err and url not in sources:
                    sources.append(url)
                results.append({"type": "tool_result", "tool_use_id": block.id, "content": text, "is_error": err})
            messages.append({"role": "user", "content": results})

    if response.stop_reason == "refusal":
        return {"reply": "Sorry, I can't help with that request.", "sources": [], "activity": activity}
    text = "".join(b.text for b in response.content if b.type == "text").strip()
    if response.stop_reason == "tool_use":
        text = (text + "\n\n" if text else "") + "*I ran out of research steps before finishing. Try a narrower question.*"
    if response.stop_reason == "max_tokens":
        text += "\n\n*(answer truncated)*"
    return {"reply": text or "I don't have an answer for that.", "sources": sources, "activity": activity,
            "model": response.model}


def _resp(status, body):
    # CORS headers are added by the function URL's CORS configuration.
    return {"statusCode": status, "headers": {"Content-Type": "application/json"}, "body": json.dumps(body)}


def lambda_handler(event, context):
    origin = (event.get("headers") or {}).get("origin", "")
    method = event.get("requestContext", {}).get("http", {}).get("method", "POST")
    if method == "OPTIONS":
        return _resp(204, {})
    if ALLOWED_ORIGINS and origin not in ALLOWED_ORIGINS:
        return _resp(403, {"error": "origin not allowed"})
    try:
        body = json.loads(event.get("body") or "{}")
        messages = clean_history(body.get("messages"))
    except (ValueError, json.JSONDecodeError, AttributeError) as e:
        return _resp(400, {"error": str(e)})

    ip = event.get("requestContext", {}).get("http", {}).get("sourceIp", "unknown")
    limited = over_limit(ip)
    if limited:
        return _resp(429, {"error": limited})

    try:
        return _resp(200, chat(messages))
    except anthropic.RateLimitError:
        return _resp(503, {"error": "The model is busy right now. Please try again in a minute."})
    except anthropic.APIStatusError as e:
        print("APIStatusError", e.status_code, getattr(e, "request_id", None), str(e)[:500])
        return _resp(502, {"error": "The assistant hit an upstream error. Please try again."})
    except anthropic.APIConnectionError as e:
        print("APIConnectionError", e)
        return _resp(502, {"error": "Couldn't reach the model. Please try again."})
